#!/usr/bin/env python3
"""Build a faithful startup glyph subset, keeping the original full font as fallback.

--verify uses only the Python standard library and never writes files. It checks
hashes, generated CSS/preload and coverage of current source codepoints. --check
also uses fontTools and Brotli to compare every output outline and metric with
the full font. No argument regenerates the subset, CSS, manifest and preload.
The complete original font and all upstream license notices remain unchanged.
"""
from __future__ import annotations

import argparse
import ctypes
import ctypes.util
import hashlib
from io import BytesIO
import json
from pathlib import Path
import re
import struct
import types

ROOT = Path(__file__).resolve().parents[2]
FULL = ROOT / 'public/fonts/fusion-pixel-12px-proportional-zh_hans.woff2'
FULL_SHA = 'b67eb7aa592622e5bc1152b800d32404bb887a1e3a2e669b0c2a873d388590d6'
OUTPUT = ROOT / 'public/fonts/fusion-pixel-startup-subset.woff2'
MANIFEST = ROOT / 'public/fonts/fusion-pixel-startup-subset.json'
CSS = ROOT / 'src/app/styles/fonts.css'
INDEX = ROOT / 'index.html'
PRELOAD = re.compile(r'(<link rel="preload" href=")[^"]+(" as="font" type="font/woff2" crossorigin\s*/>)')
LICENSES = ['FusionPixel-OFL.txt', 'FusionPixel-ArkPixel-OFL.txt', 'FusionPixel-Cubic11-OFL.txt']
SCAN_SUFFIXES = {'.ts', '.tsx', '.css', '.json'}


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_points() -> set[int]:
    # Generated CSS contains its own Unicode ranges and must not define inputs.
    paths = sorted(p for p in (ROOT / 'src').rglob('*')
                   if p.suffix in SCAN_SUFFIXES and p != CSS) + [INDEX]
    return ({ord(char) for path in paths for char in path.read_text()
             if ord(char) >= 32 and ord(char) != 127}
            | set(range(0x20, 0x7F)) | {0xA0, 0x2022, 0x2026})


def ranges(points: list[int]) -> str:
    groups = []
    for point in points:
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in groups)


def subset_url(digest: str) -> str:
    return f'/fonts/{OUTPUT.name}?v={digest}'


def css_text(points: list[int], digest: str) -> str:
    return ("/* Generated by prepare_pixel_font.py; retain the earlier full face for uncommon text. */\n"
            "@font-face {\n  font-family: 'Fusion Pixel';\n"
            f"  src: url('{subset_url(digest)}') format('woff2');\n"
            "  font-weight: 400;\n  font-style: normal;\n  font-display: swap;\n"
            f"  unicode-range: {ranges(points)};\n}}\n")


def authoring_tools():
    # The runtime has official system Brotli libraries, without its Python wheel.
    from fontTools import subset, version
    from fontTools.ttLib import TTFont
    import fontTools.ttLib.woff2 as woff2
    try:
        import brotli
        bridge = {'kind': 'Python Brotli', 'version': getattr(brotli, '__version__', 'unknown')}
    except ImportError:
        decoder_name = ctypes.util.find_library('brotlidec')
        encoder_name = ctypes.util.find_library('brotlienc')
        if not decoder_name or not encoder_name:
            raise RuntimeError('Authoring needs Brotli or system libbrotlidec/libbrotlienc; --verify does not.')
        decoder, encoder = ctypes.CDLL(decoder_name), ctypes.CDLL(encoder_name)
        decoder.BrotliDecoderDecompress.argtypes = [ctypes.c_size_t, ctypes.c_void_p,
            ctypes.POINTER(ctypes.c_size_t), ctypes.c_void_p]
        decoder.BrotliDecoderDecompress.restype = ctypes.c_int
        encoder.BrotliEncoderMaxCompressedSize.argtypes = [ctypes.c_size_t]
        encoder.BrotliEncoderMaxCompressedSize.restype = ctypes.c_size_t
        encoder.BrotliEncoderCompress.argtypes = [ctypes.c_int, ctypes.c_int, ctypes.c_int,
            ctypes.c_size_t, ctypes.c_void_p, ctypes.POINTER(ctypes.c_size_t), ctypes.c_void_p]
        encoder.BrotliEncoderCompress.restype = ctypes.c_int
        encoder.BrotliEncoderVersion.restype = ctypes.c_uint32

        def decompress(data):
            source = ctypes.create_string_buffer(data)
            size = ctypes.c_size_t(32 * 1024 * 1024)
            target = ctypes.create_string_buffer(size.value)
            if decoder.BrotliDecoderDecompress(len(data), source, ctypes.byref(size), target) != 1:
                raise RuntimeError('Bounded system Brotli decompression failed.')
            return target.raw[:size.value]

        def compress(data, mode=2, **_):
            source = ctypes.create_string_buffer(data)
            size = ctypes.c_size_t(encoder.BrotliEncoderMaxCompressedSize(len(data)))
            if not size.value or size.value > 32 * 1024 * 1024:
                raise RuntimeError('Unexpected font compression allocation.')
            target = ctypes.create_string_buffer(size.value)
            if encoder.BrotliEncoderCompress(11, 22, mode, len(data), source, ctypes.byref(size), target) != 1:
                raise RuntimeError('System Brotli font compression failed.')
            return target.raw[:size.value]

        brotli = types.SimpleNamespace(decompress=decompress, compress=compress, MODE_FONT=2, MODE_TEXT=1)
        bridge = {'kind': 'system libbrotli through ctypes', 'encoder': encoder_name,
                  'decoder': decoder_name, 'encoderVersion': encoder.BrotliEncoderVersion(),
                  'quality': 11, 'lgwin': 22}
    woff2.brotli = brotli
    woff2.haveBrotli = True
    return subset, TTFont, version, bridge


def font_metrics(font):
    fields = {
        'head': ['unitsPerEm'], 'hhea': ['ascent', 'descent', 'lineGap'],
        'vhea': ['ascent', 'descent', 'lineGap'],
        'OS/2': ['sTypoAscender', 'sTypoDescender', 'sTypoLineGap', 'usWinAscent',
                 'usWinDescent', 'sxHeight', 'sCapHeight', 'fsSelection'],
        'post': ['italicAngle', 'underlinePosition', 'underlineThickness'],
    }
    return {tag: {name: getattr(font[tag], name) for name in names if hasattr(font[tag], name)}
            for tag, names in fields.items() if tag in font}


def compare_fonts(full, output):
    from fontTools.pens.recordingPen import RecordingPen
    full_set, subset_set = full.getGlyphSet(), output.getGlyphSet()
    checked = []
    for name in output.getGlyphOrder():
        if name not in full_set:
            raise RuntimeError(f'Subset introduced a glyph: {name}')
        a, b = RecordingPen(), RecordingPen()
        full_set[name].draw(a)
        subset_set[name].draw(b)
        if a.value != b.value:
            raise RuntimeError(f'Changed glyph outline: {name}')
        metrics = {}
        for table in ('hmtx', 'vmtx'):
            if table in output:
                if full[table].metrics[name] != output[table].metrics[name]:
                    raise RuntimeError(f'Changed glyph metrics: {name}/{table}')
                metrics[table] = output[table].metrics[name]
        checked.append({'glyph': name, 'outline': a.value, 'metrics': metrics})
    if font_metrics(full) != font_metrics(output):
        raise RuntimeError('Changed global font metrics.')
    if any(full.getBestCmap().get(point) != name for point, name in output.getBestCmap().items()):
        raise RuntimeError('Changed Unicode glyph mappings.')
    return {'outputGlyphsCompared': len(checked), 'exactOutlinesAndMetrics': True,
            'globalMetrics': font_metrics(output),
            'outlineMetricDigest': sha(json.dumps(checked, sort_keys=True, separators=(',', ':')).encode())}


def verify():
    data = json.loads(MANIFEST.read_text())
    if data.get('version') != 1 or data.get('sourceSha256') != FULL_SHA or sha(FULL.read_bytes()) != FULL_SHA:
        raise RuntimeError('Original full font or subset manifest changed unexpectedly.')
    blob = OUTPUT.read_bytes()
    if (len(blob) < 48 or blob[:8] != b'wOF2OTTO' or struct.unpack('>I', blob[8:12])[0] != len(blob)
            or len(blob) != data['bytes'] or sha(blob) != data['sha256']):
        raise RuntimeError('Subset WOFF2 hash, size or header mismatch.')
    points, unsupported = data['codepoints'], data['unmappedSourceCodepoints']
    if points != sorted(set(points)) or any(not isinstance(p, int) or p < 32 or p > 0x10FFFF for p in points):
        raise RuntimeError('Invalid subset Unicode inventory.')
    missing = sorted(source_points() - set(points) - set(unsupported))
    if missing:
        raise RuntimeError('New source codepoints require subset regeneration: ' + ','.join(f'U+{p:X}' for p in missing))
    if CSS.read_text() != css_text(points, data['sha256']):
        raise RuntimeError('Generated subset CSS is stale or modified.')
    matches = PRELOAD.findall(INDEX.read_text())
    expected = f'%BASE_URL%fonts/{OUTPUT.name}?v={data["sha256"]}'
    if len(matches) != 1 or f'href="{expected}"' not in INDEX.read_text():
        raise RuntimeError('Startup font preload must match the generated CSS URL.')
    if not (ROOT / 'src/app/styles/app.css').read_text().rstrip().endswith("@import './fonts.css';"):
        raise RuntimeError('Subset face must follow the complete fallback font face.')
    for name, digest in data['licenses'].items():
        if name not in LICENSES or sha((FULL.parent / name).read_bytes()) != digest:
            raise RuntimeError('Font license notice changed.')
    if sorted(data['licenses']) != sorted(LICENSES):
        raise RuntimeError('Missing original license notice.')
    return data


def generate():
    if sha(FULL.read_bytes()) != FULL_SHA:
        raise RuntimeError('Refusing to subset an unexpected source font.')
    html = INDEX.read_text()
    if len(PRELOAD.findall(html)) != 1:
        raise RuntimeError('Expected exactly one startup font preload.')
    subset, TTFont, version, bridge = authoring_tools()
    original = TTFont(FULL, recalcTimestamp=False)
    points = sorted(source_points() & set(original.getBestCmap()))
    options = subset.Options()
    options.glyph_names = True
    options.notdef_outline = True
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    options.layout_features = ['*']
    font = TTFont(FULL, recalcTimestamp=False)
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(font)
    # Mark the derivative in internal names; the CSS alias remains Fusion Pixel.
    names = {1: 'Fusion Pixel Startup Subset', 3: 'FusionPixelStartupSubset-' + sha(json.dumps(points).encode())[:16],
             4: 'Fusion Pixel Startup Subset Regular', 6: 'FusionPixelStartupSubset-Regular', 16: 'Fusion Pixel Startup Subset'}
    for record in font['name'].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())
    font.flavor = 'woff2'
    buffer = BytesIO()
    font.save(buffer, reorderTables=True)
    blob = buffer.getvalue()
    restored = TTFont(BytesIO(blob), recalcTimestamp=False)
    comparison = compare_fonts(original, restored)
    if sorted(restored.getBestCmap()) != points:
        raise RuntimeError('Subset character inventory differs from the required set.')
    digest = sha(blob)
    data = {'version': 1, 'generatedBy': 'scripts/assets/prepare_pixel_font.py',
            'source': FULL.name, 'sourceSha256': FULL_SHA, 'sourceBytes': FULL.stat().st_size,
            'file': OUTPUT.name, 'sha256': digest, 'bytes': len(blob),
            'codepoints': points, 'unmappedSourceCodepoints': sorted(source_points() - set(original.getBestCmap())),
            'coverageScope': 'Printable characters in current src TS/TSX/JSON/CSS and index.html, excluding generated fonts.css; ASCII source/comments plus NBSP, bullet and ellipsis are included. New glyphs fail the standard-library coverage guard. Removed glyphs do not require regeneration.',
            'fallback': 'Earlier original full Fusion Pixel face covers characters outside this Unicode range when the full font contains them; characters absent from the original still use the existing family fallback.',
            'fontToolsVersion': version, 'brotli': bridge, 'comparison': comparison,
            'licenses': {name: sha((FULL.parent / name).read_bytes()) for name in LICENSES}}
    OUTPUT.write_bytes(blob)
    CSS.write_text(css_text(points, digest))
    MANIFEST.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
    INDEX.write_text(PRELOAD.sub(lambda m: m.group(1) + f'%BASE_URL%fonts/{OUTPUT.name}?v={digest}' + m.group(2), html))
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--verify', action='store_true')
    modes.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = verify() if args.verify or args.check else generate()
    if args.check:
        _, TTFont, _, _ = authoring_tools()
        comparison = compare_fonts(TTFont(FULL), TTFont(OUTPUT))
        if comparison != data['comparison']:
            raise RuntimeError('Glyph comparison differs from the manifest.')
    print(json.dumps({'status': 'passed', 'mode': 'check' if args.check else 'verify' if args.verify else 'generate',
                      'sourceBytes': data['sourceBytes'], 'subsetBytes': data['bytes'],
                      'mappedCodepoints': len(data['codepoints']), 'outputGlyphs': data['comparison']['outputGlyphsCompared'],
                      'fontBytesSaved': data['sourceBytes'] - data['bytes'], 'fullFontPreserved': True}))


if __name__ == '__main__':
    main()

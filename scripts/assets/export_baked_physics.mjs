#!/usr/bin/env node
/** Bake the default deterministic physical cycle; no browser or generated art. */
import { readFileSync, writeFileSync, readdirSync, unlinkSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { resolve, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { HAIR_NODES } from '../../src/features/portrait/renderer/hairTypes.ts'
import { readStageOptions } from '../../src/features/portrait/animation/stageOptions.ts'

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)))
const output = resolve(root, 'public/assets/portrait-rig')
const generated = resolve(root, 'src/features/portrait/renderer/bakedPhysicsManifest.ts')
const hash = data => createHash('sha256').update(data).digest('hex')
const entry = file => { const data = readFileSync(file); return { file: relative(root, file), bytes: data.length, sha256: hash(data) } }
const defaults = readStageOptions('')
const config = { direction: defaults.direction, gust: defaults.gust, stiffness: defaults.stiffness, damping: defaults.damping }
const bindingKey = (locks, size) => JSON.stringify(locks.map(({ side, spine, motion }) => [side, motion,
  Array.from(spine, value => Math.round(value / (size / 256) * 1000) / 1000)]))
const sources = ['src/features/portrait/renderer/hairPhysics.ts', 'src/features/portrait/renderer/hairTypes.ts',
  'src/features/portrait/animation/portraitTimeline.ts', 'src/features/portrait/animation/stageOptions.ts',
  'scripts/assets/export_baked_physics.mjs'].map(file => entry(resolve(root, file)))
const manifest = { version: 1, config, sources, inputs: [], files: [] }
const descriptors = {}
for (const size of [192, 256, 320]) {
  // A fresh module avoids the solver's rounded normalized-key reuse across grids.
  const { HairPhysics } = await import(`../../src/features/portrait/renderer/hairPhysics.ts?bake-grid=${size}`)
  const binding = resolve(output, `rig-${size}.json`)
  const bundle = JSON.parse(readFileSync(binding, 'utf8'))
  const locks = bundle.locks.map(lock => ({ ...lock, pixels: new Uint32Array(0), spine: new Float32Array(lock.spine) }))
  const physics = new HairPhysics(locks, config, size)
  const cache = physics.exportCache()
  const frames = cache.poses[0].length / (HAIR_NODES * 2)
  const floats = [...cache.rest, ...cache.poses]
  const binary = Buffer.alloc(64 + floats.reduce((sum, array) => sum + array.byteLength, 0))
  binary.write('VHCPv001', 0, 'ascii')
  binary.writeUInt32LE(locks.length, 8); binary.writeUInt32LE(HAIR_NODES, 12)
  binary.writeUInt32LE(frames, 16); binary.writeUInt32LE(HAIR_NODES * 2, 20)
  binary.writeDoubleLE(cache.maxLengthError, 24); binary.writeDoubleLE(cache.maxSeamDistance, 32)
  binary.writeDoubleLE(cache.maxDisplacement, 40)
  let offset = 64
  for (const array of floats) for (const value of array) { binary.writeFloatLE(value, offset); offset += 4 }
  const sha256 = hash(binary), file = `wind-default-${sha256.slice(0, 16)}.bin`
  const path = resolve(output, file)
  writeFileSync(path, binary)
  manifest.inputs.push(entry(binding)); if (!manifest.files.some(item => item.file === relative(root, path))) manifest.files.push(entry(path))
  descriptors[size] = { file, bytes: binary.length, sha256, bindingSha256: hash(bindingKey(locks, size)), locks: locks.length, nodes: HAIR_NODES, frames }
  console.log(`${size}: ${binary.length} bytes, ${frames} cached frames, SHA256 ${sha256}`)
}
// Remove only superseded outputs owned by this exporter, after all sizes exist.
const retained = new Set(Object.values(descriptors).map(item => item.file))
for (const name of readdirSync(output)) if (/^wind-default-[a-f0-9-]+\.bin$/.test(name) && !retained.has(name)) unlinkSync(resolve(output, name))
writeFileSync(generated, `// Generated by scripts/assets/export_baked_physics.mjs; do not edit.\nexport const bakedPhysicsConfig = ${JSON.stringify(config)} as const\nexport const bakedPhysicsManifest = ${JSON.stringify(descriptors, null, 2)} as const\n`)
manifest.files.push(entry(generated))
writeFileSync(resolve(output, 'physics-manifest.json'), JSON.stringify(manifest, null, 2) + '\n')

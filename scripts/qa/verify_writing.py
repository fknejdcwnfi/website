#!/usr/bin/env python3
"""Check the shared public writing space, including native no-JS reading."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit
from playwright.sync_api import sync_playwright

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--url', default='http://127.0.0.1:5180/')
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()
args.output.mkdir(parents=True, exist_ok=True)
report = {'status': 'failed', 'url': args.url, 'checks': [], 'errors': [], 'badResponses': [], 'layouts': []}


def check(name, condition, detail=None):
    report['checks'].append({'name': name, 'passed': bool(condition), 'detail': detail})
    (args.output / 'checks.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
    if not condition:
        raise AssertionError(name)


def observe(page):
    page.on('pageerror', lambda error: report['errors'].append(str(error)))
    page.on('response', lambda response: report['badResponses'].append({'url': response.url, 'status': response.status}) if response.status >= 400 else None)


with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width': 1440, 'height': 1100}, reduced_motion='reduce')
    context.add_init_script("try { localStorage.setItem('vermouth-scene-motion','static') } catch (_) {}")
    page = context.new_page()
    observe(page)
    response = page.goto(args.url)
    check('preview_http_200', response.status == 200)
    page.wait_for_selector('.personal-site:not(.static-site)')
    article = page.locator('#note-transition-day')
    reading = article.locator('details')
    summary = reading.locator('summary')
    check('single_public_note', article.count() == 1)
    newer = page.locator('#note-keeping-pace')
    latest = page.locator('#note-keep-time-moving')
    index = page.get_by_role('navigation', name='本栏索引')
    expected_links = ['#note-keep-time-moving', '#thought-rebuild-direction', '#note-transition-day', '#note-keeping-pace']
    check('four_public_entries_share_one_space', page.locator('#writing .writing-entry').count() == 4 and newer.count() == 1)
    check('writing_index_matches_current_article_order', index.get_by_role('link').evaluate_all('links=>links.map(a=>a.hash)') == expected_links)
    check('latest_log_records_only_its_writing_date', latest.locator('time').evaluate_all('nodes=>nodes.map(e=>e.dateTime)') == ['2026-11-20'])
    index.get_by_role('link', name='让时间继续向前').focus()
    page.keyboard.press('Enter')
    page.wait_for_url('**/#note-keep-time-moving')
    check('index_keyboard_navigation_focuses_latest_log', page.evaluate('document.activeElement.id') == 'note-keep-time-moving')
    latest.locator('summary').focus()
    page.keyboard.press('Space')
    check('latest_log_native_reading', latest.locator('details').get_attribute('open') is not None and latest.locator('.writing-entry__chapter').count() == 4)
    latest.locator('summary').click()
    check('one_shared_writing_navigation_target', page.locator('.site-header__nav a[href="#writing"]').count() == 1 and page.locator('#journal,#thoughts').count() == 2)
    check('category_labels_distinguish_logs_and_thoughts', page.locator('#writing .writing-entry__kind').all_text_contents() == ['日志', '思绪', '日志', '日志'])
    check('undated_original_has_no_invented_time', newer.locator('time').count() == 0 and '原稿未注明日期' in newer.inner_text())
    check('no_raw_document_download', page.locator('a[href$=".docx"]').count() == 0)
    check('seven_navigation_targets', page.locator('.site-header__nav a').evaluate_all('(links)=>links.map(a=>a.hash)') == ['#home', '#about', '#work', '#writing', '#interests', '#games', '#contact'])
    thoughts = page.locator('#thought-rebuild-direction')
    check('thoughts_share_space_and_keep_their_date', page.locator('#writing').count() == 1 and
          thoughts.count() == 1 and thoughts.locator('time').evaluate('(e)=>e.dateTime') == '2026-11-18')
    thought_search = page.get_by_role('searchbox', name='搜索此网站')
    thought_search.fill('时间的停滞和延迟')
    page.wait_for_selector('#site-search-results .site-search__result[href="#note-keep-time-moving"]')
    page.keyboard.press('Enter')
    check('new_log_search_matches_full_body_text', page.evaluate('document.activeElement.id') == 'note-keep-time-moving')
    thought_search.fill('三色')
    page.wait_for_selector('#site-search-results .site-search__result[href="#thought-rebuild-direction"]')
    check('thoughts_and_logs_share_one_search_group', page.locator('#site-search-results .site-search__group-label').filter(has_text='思绪与日志').count() == 1)
    check('thoughts_privacy_edition_and_edited_copy', '思绪整理' in thoughts.locator('.writing-entry__body').text_content() and
          '重新联系导师' in thoughts.locator('.writing-entry__body').text_content() and '名字和具体安排留给我自己' in thoughts.locator('.writing-entry__body').text_content())
    page.keyboard.press('Enter')
    check('thought_search_focuses_its_own_article', page.evaluate('document.activeElement.id') == 'thought-rebuild-direction' and
          page.locator('.personal-site').get_attribute('data-active-section') == 'writing')
    thoughts.screenshot(path=str(args.output / 'thought-card.png'))
    check('separate_dates', article.locator('time').evaluate_all('(nodes)=>nodes.map(e=>e.dateTime)') == ['2026-11-14', '2026-11-15'])
    check('collapsed_initial_reading', reading.get_attribute('open') is None)
    page.locator('.site-header__nav a[href="#writing"]').click()
    check('writing_active', page.locator('.personal-site').get_attribute('data-active-section') == 'writing')
    summary.focus()
    page.keyboard.press('Enter')
    check('keyboard_expands_native_reading', reading.get_attribute('open') is not None)
    check('six_readable_chapters', article.locator('.writing-entry__chapter').count() == 6 and article.locator('.writing-entry__chapter').first.is_visible())
    check('edited_version_label', '日志整理' in article.inner_text())
    check('no_location_or_embedded_document_metadata', article.locator('address,a[href^="geo:"],iframe,embed,object').count() == 0)
    check('learning_is_not_claimed_complete', '需要准备考试' in article.text_content() and '我想联系学术导师' in article.text_content())
    check('existing_game_preserved', page.locator('#game-honor-of-kings').count() == 1)
    for width in [320, 375, 541, 768, 801, 1440, 1680]:
        page.set_viewport_size({'width': width, 'height': 1000})
        # The character viewport can briefly retain its prior backing size
        # until ResizeObserver and one render frame settle after resize.
        page.evaluate('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
        article.scroll_into_view_if_needed()
        if width == 375:
            thoughts.scroll_into_view_if_needed()
            thoughts.screenshot(path=str(args.output / 'thought-card-mobile.png'))
            latest.screenshot(path=str(args.output / 'latest-card-mobile.png'))
            index.evaluate('node=>node.scrollIntoView({block:"center"})')
            index.screenshot(path=str(args.output / 'index-mobile.png'))
        if width == 320:
            check('320_index_keeps_44px_link_targets', index.get_by_role('link').evaluate_all('links=>links.every(a=>a.getBoundingClientRect().height>=44)'))
            page.locator('.writing-entry__reading').evaluate_all('nodes=>nodes.forEach(node=>{node.open=true})')
        layout = page.evaluate('''() => ({width:innerWidth,scroll:document.documentElement.scrollWidth,
          bounds:[...document.querySelectorAll('.writing-space__index,.writing-space__index a,.writing-entry,.writing-entry__reading,.writing-entry__body,.writing-entry__chapter')].map(e=>{const r=e.getBoundingClientRect();return {x:r.x,right:r.right}}),
          header:[...document.querySelectorAll('.site-header__nav a')].map(e=>{const r=e.getBoundingClientRect();return {x:r.x,right:r.right}})})''')
        report['layouts'].append(layout)
        check(f'{width}_no_overflow', layout['scroll'] <= width and all(e['x'] >= 0 and e['right'] <= width + .5 for e in layout['bounds'] + layout['header']))
        if width == 320:
            page.locator('.writing-entry__reading').evaluate_all('nodes=>nodes.forEach(node=>{node.open=node.closest("article").id==="note-transition-day"})')
    page.set_viewport_size({'width': 1440, 'height': 1100})
    style = article.evaluate('e=>{const s=getComputedStyle(e);return {radius:s.borderRadius,border:s.borderTopWidth,font:s.fontFamily}}')
    check('shared_card_border_and_pixel_font', style['radius'] == '14px' and style['border'] == '1px' and 'Fusion Pixel' in style['font'], style)
    summary.focus()
    page.keyboard.press('Space')
    check('keyboard_collapses_reading', reading.get_attribute('open') is None)
    search = page.get_by_role('searchbox', name='搜索此网站')
    search.fill('Verilog')
    check('full_text_search_group', page.locator('#site-search-results .site-search__group-label').filter(has_text='思绪与日志').count() == 1)
    page.keyboard.press('Enter')
    check('search_focuses_visible_article', page.evaluate('document.activeElement.id') == 'note-transition-day' and page.locator('.personal-site').get_attribute('data-active-section') == 'writing')
    article.screenshot(path=str(args.output / 'log-card.png'))
    context.close()
    # Normal motion verifies that reading and navigation keep the actual player.
    context = browser.new_context(viewport={'width': 1440, 'height': 1100}, reduced_motion='no-preference')
    page = context.new_page()
    observe(page)
    page.goto(args.url)
    page.wait_for_selector('.reference-scene__canvas', state='attached')
    page.evaluate('window.__journalCanvas=document.querySelector(".reference-scene__canvas")')
    page.locator('.site-header__nav a[href="#writing"]').click()
    page.locator('#note-transition-day .writing-entry__reading summary').click()
    page.locator('.site-header__nav a[href="#home"]').click()
    check('same_character_canvas', page.evaluate('window.__journalCanvas===document.querySelector(".reference-scene__canvas")'))
    page.locator('.site-header__nav a[href="#writing"]').click()
    page.locator('#thought-rebuild-direction .writing-entry__reading summary').click()
    check('writing_navigation_keeps_same_character_canvas', page.evaluate('window.__journalCanvas===document.querySelector(".reference-scene__canvas")'))
    context.close()
    context = browser.new_context(java_script_enabled=False, viewport={'width': 375, 'height': 1000})
    page = context.new_page()
    observe(page)
    page.goto(args.url + '#note-transition-day')
    index = page.get_by_role('navigation', name='本栏索引')
    check('no_js_index_has_same_targets', index.get_by_role('link').evaluate_all('links=>links.map(a=>a.hash)') == expected_links)
    index.get_by_role('link', name='让时间继续向前').click()
    page.wait_for_url('**/#note-keep-time-moving')
    latest = page.locator('#note-keep-time-moving')
    latest.locator('summary').click()
    check('no_js_latest_log_complete', latest.locator('details').get_attribute('open') is not None and latest.locator('.writing-entry__chapter').count() == 4 and '时间的停滞和延迟' in latest.inner_text())
    reading = page.locator('#note-transition-day .writing-entry__reading')
    reading.locator('summary').click()
    check('no_js_full_native_reading', reading.get_attribute('open') is not None and reading.locator('.writing-entry__chapter').count() == 6)
    newer = page.locator('#note-keeping-pace')
    newer.locator('summary').click()
    check('no_js_new_article_reading', newer.locator('details').get_attribute('open') is not None and newer.locator('.writing-entry__chapter').count() == 5 and newer.locator('time').count() == 0)
    thoughts = page.locator('#thought-rebuild-direction')
    thoughts.locator('.writing-entry__reading summary').click()
    check('no_js_thoughts_full_reading', thoughts.locator('details').get_attribute('open') is not None and thoughts.locator('.writing-entry__chapter').count() == 5)
    check('no_js_no_dead_search', page.get_by_role('searchbox').count() == 0)
    check('no_js_pixel_font', 'Fusion Pixel' in reading.locator('.writing-entry__body').evaluate('e=>getComputedStyle(e).fontFamily'))
    check('no_js_local_resources', all(urlsplit(src).hostname == urlsplit(args.url).hostname for src in page.locator('img').evaluate_all('(imgs)=>imgs.map(e=>e.src)')))
    context.close()
    browser.close()
check('no_browser_errors', not report['errors'], report['errors'])
check('no_bad_responses', not report['badResponses'], report['badResponses'])
report['status'] = 'passed'
(args.output / 'checks.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
print(json.dumps({'status': report['status'], 'checks': len(report['checks']), 'url': args.url}))
